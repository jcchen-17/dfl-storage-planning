"""Build the second-generation storage-planning scenario dataset.

The first dataset concatenated unrelated hourly sources and then treated the
result as jointly observed history.  This builder keeps the useful Smart-DS
load/PV/weather trajectories, but makes every cross-source assumption explicit:

* 48-hour windows do not overlap;
* EIA carbon stays in contiguous 48-hour blocks and is reassigned only within
  the same season, breaking the accidental hour-for-hour correlation with
  Smart-DS load and weather;
* the 14-day Azure trace becomes a deterministic median intraday template until
  a longer power/workload trace is supplied -- it is not repeated and presented
  as three years of independent observations;
* price and PUE remain in the planning-ready file, but are marked as
  deterministic derived fields and must not be generated by a scenario model;
* reactive power is rebuilt at the IEEE13 phase power factors instead of being
  independently normalized and independently peak-scaled from active power.

The old processed data are read-only inputs.  Outputs go to a new directory and
the builder refuses to overwrite them unless ``--force`` is passed.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pyarrow.parquet as pq

from storage_dfl.network import ieee13_unbalanced_microgrid


BUSES = (
    "650", "632", "633", "634", "645", "646", "671", "680", "684",
    "611", "652", "692", "675",
)
PHASES = ("A", "B", "C")
SEASONS = {
    12: "winter", 1: "winter", 2: "winter",
    3: "spring", 4: "spring", 5: "spring",
    6: "summer", 7: "summer", 8: "summer",
    9: "autumn", 10: "autumn", 11: "autumn",
}
SPLIT_SEEDS = {"train": 1701, "validation": 2701, "test": 3701}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("data/processed/ieee13_smartds_dfl/dfl_hourly_wide.parquet"),
        help="Existing fused hourly table; it is never modified.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("data/processed/ieee13_smartds_dfl_v2"),
    )
    parser.add_argument("--horizon", type=int, default=48)
    parser.add_argument("--seed", type=int, default=20260808)
    parser.add_argument("--force", action="store_true")
    parser.add_argument(
        "--outage-window-fraction",
        type=float,
        default=0.0,
        help=(
            "Share of windows in each split given a grid outage. 0.0 reproduces "
            "the original all-available dataset. This is deliberately far above "
            "the physical rate so a 182-window split contains enough outages to "
            "select among; --outage-annual-frequency records the real rate and "
            "sample_weight carries the importance correction."
        ),
    )
    parser.add_argument(
        "--outage-annual-frequency",
        type=float,
        default=1.3,
        help=(
            "True sustained interruptions per year (US distribution SAIFI is "
            "about 1.3). Only used to compute the importance weights, never to "
            "decide how many windows get an outage."
        ),
    )
    parser.add_argument("--outage-min-hours", type=int, default=2)
    parser.add_argument("--outage-max-hours", type=int, default=10)
    return parser.parse_args()


def outage_assignment(
    window_splits: np.ndarray,
    horizon: int,
    fraction: float,
    min_hours: int,
    max_hours: int,
    seed: int,
) -> tuple[np.ndarray, np.ndarray]:
    """Give a share of each split one contiguous outage.

    Contiguous rather than per-hour Bernoulli: a battery sized for scattered
    single missing hours is a different machine from one that has to carry a
    sustained interruption, and only the second is what a data centre buys.
    Drawn per split so a split's outage set does not depend on how many windows
    the other splits happen to have.
    """

    count = len(window_splits)
    available = np.ones((count, horizon), dtype=np.float32)
    duration = np.zeros(count, dtype=np.int16)
    if fraction <= 0.0:
        return available, duration
    if not 0.0 < fraction <= 1.0:
        raise ValueError("--outage-window-fraction must lie in (0, 1].")
    if not 1 <= min_hours <= max_hours <= horizon:
        raise ValueError(
            "Outage duration must satisfy 1 <= min <= max <= horizon, got "
            f"{min_hours}..{max_hours} against horizon {horizon}."
        )

    for split in np.unique(window_splits):
        indices = np.flatnonzero(window_splits == split)
        rng = np.random.default_rng(seed + SPLIT_SEEDS.get(str(split), 4701))
        chosen = rng.choice(
            indices, size=int(round(fraction * indices.size)), replace=False
        )
        for index in chosen:
            hours = int(rng.integers(min_hours, max_hours + 1))
            # The outage may run past the window end; truncating it there would
            # bias durations short exactly for the late starts.
            start = int(rng.integers(0, horizon))
            available[index, start : start + hours] = 0.0
            duration[index] = int(horizon - start if start + hours > horizon else hours)
    return available, duration


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _portable_path(path: Path) -> str:
    """Prefer a workspace-relative manifest path when one is available."""

    try:
        return path.resolve().relative_to(Path.cwd().resolve()).as_posix()
    except ValueError:
        return str(path.resolve())


def _column(table, name: str) -> np.ndarray:
    return np.asarray(table[name].combine_chunks().to_numpy(zero_copy_only=False))


def _season(month: int) -> str:
    return SEASONS[int(month)]


def non_overlapping_starts(years: np.ndarray, horizon: int) -> np.ndarray:
    """Return horizon-aligned starts without crossing a calendar year."""

    starts: list[int] = []
    for year in np.unique(years):
        indices = np.flatnonzero(years == year)
        if indices.size < horizon or np.any(np.diff(indices) != 1):
            raise ValueError(f"Year {year} is not one contiguous hourly block.")
        starts.extend(
            int(indices[0] + local)
            for local in range(0, indices.size - horizon + 1, horizon)
        )
    return np.asarray(starts, dtype=np.int32)


def constant_power_factor_reactive(active: np.ndarray) -> np.ndarray:
    """Rebuild Q from P at the IEEE13 component power factors.

    The v1 preprocessing normalized Smart-DS P and Q independently and then
    independently forced their feeder peaks.  That changed power factors.  A
    static IEEE13 phase power factor is less ambitious but physically explicit
    and preserves Q/P exactly at every occupied phase.
    """

    feeder = ieee13_unbalanced_microgrid()
    if tuple(feeder.buses) != BUSES or tuple(feeder.phases) != PHASES:
        raise ValueError("Dataset bus/phase order no longer matches the feeder.")
    ratio = np.divide(
        feeder.base_reactive_load_mvar,
        feeder.base_active_load_mw,
        out=np.zeros_like(feeder.base_reactive_load_mvar),
        where=feeder.base_active_load_mw > 0.0,
    )
    return (active * ratio[None, :, :]).astype(np.float32)


def median_intraday_workload(workload: np.ndarray, hours: np.ndarray) -> np.ndarray:
    """Collapse the short repeated proxy trace to an honest 24-hour template."""

    template = np.asarray(
        [np.median(workload[hours == hour]) for hour in range(24)],
        dtype=np.float32,
    )
    return template[hours.astype(int)]


def seasonal_carbon_assignment(
    carbon_windows: np.ndarray,
    months: np.ndarray,
    splits: np.ndarray,
    seed: int,
) -> tuple[np.ndarray, np.ndarray]:
    """Permute intact carbon blocks within season and split.

    This preserves each observed 48-hour carbon trajectory and its split year,
    while removing the unsupported claim that it occurred at the same instant
    as the independently sourced Smart-DS load/PV/weather trajectory.
    """

    assigned = np.empty_like(carbon_windows)
    source_index = np.empty(carbon_windows.shape[0], dtype=np.int32)
    for split in np.unique(splits):
        for season in sorted(set(SEASONS.values())):
            members = np.asarray(
                [
                    index
                    for index in range(len(months))
                    if splits[index] == split and _season(int(months[index])) == season
                ],
                dtype=np.int32,
            )
            if members.size == 0:
                continue
            local_seed = seed + SPLIT_SEEDS.get(str(split), 4701) + sum(map(ord, season))
            rng = np.random.default_rng(local_seed)
            permuted = rng.permutation(members)
            assigned[members] = carbon_windows[permuted]
            source_index[members] = permuted
    return assigned, source_index


def main() -> None:
    args = parse_args()
    if args.horizon <= 0 or 8760 % args.horizon != 24:
        # The final 24 hours of a 365-day year are deliberately left unused for
        # a 48-hour horizon; reject unusual horizons rather than silently making
        # a split-dependent remainder policy.
        raise ValueError("v2 currently expects a horizon with a 24-hour annual remainder.")

    input_path = args.input.resolve()
    output_dir = args.output_dir.resolve()
    dataset_path = output_dir / f"dfl_scenarios_v2_{args.horizon}h.npz"
    manifest_path = output_dir / "manifest_v2.json"
    if not input_path.exists():
        raise FileNotFoundError(input_path)
    if not args.force and (dataset_path.exists() or manifest_path.exists()):
        raise FileExistsError(
            f"Refusing to overwrite v2 outputs in {output_dir}; pass --force explicitly."
        )

    table = pq.read_table(input_path)
    years = _column(table, "year").astype(np.int16)
    row_splits = _column(table, "split").astype(str)
    months_hourly = _column(table, "month").astype(np.int8)
    hours = _column(table, "hour").astype(np.int8)
    weekend = _column(table, "is_weekend").astype(np.float32)
    temperature = _column(table, "temperature_c").astype(np.float32)
    timestamps = _column(table, "timestamp").astype("datetime64[h]")

    starts = non_overlapping_starts(years, args.horizon)
    stops = starts + args.horizon

    def windows(values: np.ndarray) -> np.ndarray:
        return np.stack([values[start:stop] for start, stop in zip(starts, stops, strict=True)]).astype(np.float32)

    active_hourly = np.stack(
        [
            _column(table, f"active_load_mw__{bus}__{phase}")
            for bus in BUSES for phase in PHASES
        ],
        axis=1,
    ).reshape(-1, len(BUSES), len(PHASES)).astype(np.float32)
    pv_hourly = np.stack(
        [
            _column(table, f"pv_available_mw__{bus}__{phase}")
            for bus in BUSES for phase in PHASES
        ],
        axis=1,
    ).reshape(-1, len(BUSES), len(PHASES)).astype(np.float32)
    reactive_hourly = constant_power_factor_reactive(active_hourly)

    active = windows(active_hourly)
    reactive = windows(reactive_hourly)
    pv = windows(pv_hourly)
    price = windows(_column(table, "grid_price_per_mwh"))
    pue = windows(np.clip(1.15 + 0.006 * np.maximum(temperature - 18.0, 0.0), 1.15, 1.35))
    workload_template = median_intraday_workload(
        _column(table, "workload_arrival").astype(np.float32), hours
    )
    workload = windows(workload_template)
    observed_carbon = windows(_column(table, "grid_carbon_t_per_mwh"))

    window_years = years[starts]
    window_splits = row_splits[starts]
    window_months = months_hourly[starts]
    carbon, carbon_source_index = seasonal_carbon_assignment(
        observed_carbon, window_months, window_splits, args.seed
    )

    contexts = np.empty((len(starts), 4), dtype=np.float32)
    for index, (start, stop) in enumerate(zip(starts, stops, strict=True)):
        day = int((timestamps[start] - np.datetime64(f"{int(years[start])}-01-01", "h")) / np.timedelta64(24, "h"))
        angle = 2.0 * np.pi * day / 365.0
        contexts[index] = (
            np.sin(angle),
            np.cos(angle),
            float(weekend[start:stop].mean()),
            float(temperature[start:stop].mean()),
        )

    names = np.asarray(
        [f"v2_{int(years[start])}_{index:03d}_{args.horizon}h" for index, start in enumerate(starts)]
    )
    source_names = np.asarray(
        [f"eia_block_{int(window_years[index])}_{int(source):03d}" for index, source in enumerate(carbon_source_index)]
    )
    group_ids = np.asarray(
        [f"{int(years[start])}_block_{index:03d}" for index, start in enumerate(starts)]
    )
    start_timestamps = timestamps[starts].astype("datetime64[h]").astype(str)
    grid_available, outage_hours = outage_assignment(
        window_splits,
        args.horizon,
        args.outage_window_fraction,
        args.outage_min_hours,
        args.outage_max_hours,
        args.seed,
    )
    has_outage = outage_hours > 0

    split_weights = np.asarray(
        [1.0 / np.count_nonzero(window_splits == split) for split in window_splits],
        dtype=np.float32,
    )
    # Outages are simulated far more often than they occur so that a split
    # contains enough of them to choose among. Left uncorrected, any weighted
    # average over the pool would then price a rare event as a common one, so
    # the oversampling is undone here and the two classes keep their true shares.
    true_probability = float(
        1.0 - np.exp(-args.outage_annual_frequency * args.horizon / 8760.0)
    )
    if has_outage.any():
        for split in np.unique(window_splits):
            in_split = window_splits == split
            outage = in_split & has_outage
            normal = in_split & ~has_outage
            simulated = outage.sum() / in_split.sum()
            split_weights[outage] *= true_probability / simulated
            if normal.any():
                split_weights[normal] *= (1.0 - true_probability) / (1.0 - simulated)

    payload = {
        "dataset_version": np.asarray("2.0"),
        "scenario_name": names,
        "split": window_splits,
        "sample_weight": split_weights,
        "group_id": group_ids,
        "start_timestamp": start_timestamps,
        "source_year": window_years,
        "carbon_source_block": source_names,
        "context": contexts,
        "context_names": np.asarray(
            ["start_doy_sin", "start_doy_cos", "weekend_fraction", "mean_temperature_c"]
        ),
        "active_load_phase_mw": active,
        "reactive_load_phase_mvar": reactive,
        "pv_available_phase_mw": pv,
        "active_load_mw": active.sum(axis=3),
        "reactive_load_mvar": reactive.sum(axis=3),
        "pv_available_mw": pv.sum(axis=3),
        "workload_arrival": workload,
        "pue": pue,
        "grid_price_per_mwh": price,
        "grid_carbon_t_per_mwh": carbon,
        "grid_available": grid_available,
        "outage_hours": outage_hours,
        "buses": np.asarray(BUSES),
        "phases": np.asarray(PHASES),
        "deterministic_fields": np.asarray(
            ["workload_arrival", "pue", "grid_price_per_mwh"]
            + ([] if has_outage.any() else ["grid_available"])
        ),
        "stochastic_fields": np.asarray(
            ["active_load_phase_mw", "reactive_load_phase_mvar", "pv_available_phase_mw", "grid_carbon_t_per_mwh"]
            + (["grid_available"] if has_outage.any() else [])
        ),
    }

    output_dir.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(dataset_path, **payload)

    split_counts = {
        str(split): int(np.count_nonzero(window_splits == split))
        for split in np.unique(window_splits)
    }
    carbon_changed = np.asarray(
        [not np.array_equal(carbon[index], observed_carbon[index]) for index in range(len(carbon))]
    )
    manifest = {
        "dataset_version": "2.0",
        "dataset": _portable_path(dataset_path),
        "dataset_sha256": _sha256(dataset_path),
        "source_hourly_table": _portable_path(input_path),
        "source_hourly_sha256": _sha256(input_path),
        "horizon_hours": args.horizon,
        "stride_hours": args.horizon,
        "overlap_hours": 0,
        "scenario_count": len(starts),
        "split_counts": split_counts,
        "seed": args.seed,
        "sources": {
            "network": "IEEE PES IEEE13",
            "load_pv_temperature": "SMART-DS GSO industrial 2016-2018",
            "workload": "Azure Functions 2019 14-day trace collapsed to a deterministic median 24-hour template",
            "price": "OpenEI OPT-V 2026 tariff, deterministically expanded by local calendar",
            "pue": "deterministic temperature formula",
            "carbon": "EIA-930 DUK 2021-2023 consumed-electricity intensity; intact 48-hour blocks permuted within split and season",
        },
        "joint_observation_claim": False,
        "deterministic_fields": payload["deterministic_fields"].tolist(),
        "stochastic_fields": payload["stochastic_fields"].tolist(),
        "reactive_power_method": "active power times static IEEE13 phase Q/P ratio",
        "carbon_blocks_reassigned": int(carbon_changed.sum()),
        "carbon_blocks_unchanged_by_chance": int((~carbon_changed).sum()),
        "outages": {
            "window_fraction_simulated": args.outage_window_fraction,
            "windows_with_outage": int(has_outage.sum()),
            "duration_hours_range": [args.outage_min_hours, args.outage_max_hours],
            "mean_duration_hours": (
                float(outage_hours[has_outage].mean()) if has_outage.any() else 0.0
            ),
            "assumed_annual_frequency": args.outage_annual_frequency,
            "true_window_probability": true_probability,
            "importance_weighted": bool(has_outage.any()),
        },
        "known_limitations": [
            "The workload is a deterministic proxy pending a longer data-center power trace.",
            "Carbon and Smart-DS trajectories are scenario components, not jointly observed measurements.",
            (
                "Outages are simulated at a rate far above the assumed SAIFI and "
                "corrected through sample_weight; nothing in the training or "
                "evaluation pipeline reads sample_weight yet, so any weighted "
                "result must apply it explicitly."
                if has_outage.any()
                else "Grid availability is one; outage scenarios require a separately weighted stress-test set."
            ),
            "Outage timing is independent of load, PV and carbon, so storm-driven correlation between demand and interruption is not represented.",
            "Customer tariff and carbon series describe different economic/accounting quantities and are not jointly observed.",
        ],
    }
    manifest_path.write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False, allow_nan=False),
        encoding="utf-8",
    )

    print(f"dataset: {dataset_path}")
    print(f"scenarios: {len(starts)} {split_counts}")
    print(f"horizon/stride/overlap: {args.horizon}/{args.horizon}/0 h")
    print(f"carbon blocks reassigned: {int(carbon_changed.sum())}/{len(carbon_changed)}")
    if has_outage.any():
        print(
            f"outages: {int(has_outage.sum())}/{len(has_outage)} windows, "
            f"{outage_hours[has_outage].min()}-{outage_hours[has_outage].max()} h "
            f"(mean {outage_hours[has_outage].mean():.1f}); "
            f"true window probability {true_probability:.4f}, "
            f"importance weight {split_weights[has_outage][0] / split_weights[~has_outage][0]:.4f}x"
        )
    print(f"manifest: {manifest_path}")


if __name__ == "__main__":
    main()
